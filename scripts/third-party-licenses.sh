#!/usr/bin/env bash
# Regenerates third_party/licenses.csv (inventory) and
# third_party/THIRD_PARTY_LICENSES.txt (all license and NOTICE texts in one file)
# for every module compiled into a release binary.
#
# The module set is the union of `go list -deps` over the exact GoReleaser
# targets (CGO_ENABLED=0, linux/darwin/windows x amd64/arm64), so OS-specific
# dependencies are covered. Texts come from the module cache; a module that
# ships no license file must have one in third_party/supplemental/ (with the
# provenance recorded in docs/dev/releasing.md), otherwise this script fails.
set -euo pipefail
# Same ordering locally and in CI, so the committed output can be diffed.
export LC_ALL=C

repo="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
out="$repo/third_party"
bundle="$out/THIRD_PARTY_LICENSES.txt"
csv="$out/licenses.csv"
targets=(linux/amd64 linux/arm64 darwin/amd64 darwin/arm64 windows/amd64 windows/arm64)

cd "$repo"
self="$(go list -m)"
work="$(mktemp -d)"
trap 'rm -rf "$work"' EXIT

for target in "${targets[@]}"; do
  CGO_ENABLED=0 GOOS="${target%/*}" GOARCH="${target#*/}" \
    go list -deps -f '{{with .Module}}{{.Path}} {{.Version}}{{end}}' . |
    sort -u | grep -v '^$' | grep -v "^$self " |
    sed "s|\$| ${target}|" >>"$work/rows"
done

# classify <file> prints the SPDX ids whose canonical text appears in the file.
classify() {
  local file="$1"
  grep -q 'Apache License' "$file" && grep -q 'Version 2.0' "$file" && echo "Apache-2.0"
  grep -q 'Permission is hereby granted, free of charge' "$file" && echo "MIT"
  if grep -q 'Redistribution and use in source and binary forms' "$file"; then
    if grep -q 'Neither the name' "$file"; then echo "BSD-3-Clause"; else echo "BSD-2-Clause"; fi
  fi
  return 0
}

license_dir() {
  local module="$1" version="$2" dir
  dir="$(go list -m -f '{{.Dir}}' "$module@$version" 2>/dev/null || go list -m -f '{{.Dir}}' "$module")"
  if ls "$dir" | grep -Eqi '^(licen[cs]e|copying|notice)'; then echo "$dir"; return; fi
  [ -d "$out/supplemental/$module" ] || { echo "no license file for $module@$version and no supplemental text" >&2; exit 1; }
  echo "$out/supplemental/$module"
}

# append_texts <module> <version> <license> <file>... adds one bundle section.
append_texts() {
  local module="$1" version="$2" license="$3"
  shift 3
  {
    printf '================================================================================\n'
    printf '%s %s (%s)\n' "$module" "$version" "$license"
    printf '================================================================================\n\n'
    for f in "$@"; do
      printf -- '--- %s ---\n\n' "$(basename "$f")"
      cat "$f"
      printf '\n\n'
    done
  } >>"$bundle"
}

echo "module,version,license,targets" >"$csv"
cat >"$bundle" <<'HEADER'
Third-party licenses for dtui

The license and NOTICE texts of the open source modules compiled into the dtui
release binaries (linux, darwin and windows on amd64 and arm64). Generated by
scripts/third-party-licenses.sh; third_party/licenses.csv lists each module,
version, license and the targets it is built into.

HEADER

awk '{print $1" "$2}' "$work/rows" | sort -u | while read -r module version; do
  dir="$(license_dir "$module" "$version")"
  ids=""
  files=()
  for f in "$dir"/*; do
    name="$(basename "$f")"
    echo "$name" | grep -Eqi '^(licen[cs]e|copying|notice)' || continue
    [ -f "$f" ] || continue
    # dtctl's NOTICE lists dtctl's own (mostly unrelated) dependencies; only its
    # leading attribution applies to dtui and is reproduced in the root NOTICE.
    [ "$module/$name" = "github.com/dynatrace-oss/dtctl/NOTICE" ] && continue
    files+=("$f")
    ids="$ids $(classify "$f")"
  done
  license="$(echo "$ids" | tr ' ' '\n' | grep -v '^$' | sort -u | paste -sd'|' - | sed 's/|/ AND /g')"
  [ -n "$license" ] || { echo "could not classify license of $module@$version" >&2; exit 1; }
  append_texts "$module" "$version" "$license" "${files[@]}"
  covering="$(grep "^$module $version " "$work/rows" | awk '{print $3}' | paste -sd' ' -)"
  echo "$module,$version,$license,$covering" >>"$csv"
done

# The release builds with the toolchain from go.mod (setup-go go-version-file),
# and distribution toolchains do not all ship Go's LICENSE, so it is supplemental.
append_texts "go-standard-library" "$(go list -m -f '{{.GoVersion}}')" "BSD-3-Clause" "$out/supplemental/go-standard-library/LICENSE"
echo "go-standard-library,$(go list -m -f '{{.GoVersion}}'),BSD-3-Clause,${targets[*]}" >>"$csv"
